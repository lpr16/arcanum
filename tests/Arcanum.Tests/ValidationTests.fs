namespace Arcanum.Tests

open Xunit
open Arcanum.Core
open Arcanum.Asymmetric

module ValidationTests =

    // EllipticCurve.toy, toy2, and toy3 are small curves over F_17 and are not secure groups.

    let private nonInfinityPoints (curve: EllipticCurve.Curve) =
        [ for x in 0I .. curve.P - 1I do
            for y in 0I .. curve.P - 1I do
                let pt = EllipticCurve.Point(x, y)
                if EllipticCurve.isOnCurve curve pt then
                    yield pt ]

    [<Fact>]
    let ``Phase 59 - SEC 1 validatePublicKey on toy3, toy, and toy2`` () =
        let toy3Points = nonInfinityPoints EllipticCurve.toy3
        Assert.Equal(18, toy3Points.Length)
        for pt in toy3Points do
            Assert.Equal(Ok (), EllipticCurve.validatePublicKey EllipticCurve.toy3 pt)

        match EllipticCurve.validatePublicKey EllipticCurve.toy3 EllipticCurve.Infinity with
        | Error _ -> ()
        | Ok () -> Assert.Fail("Expected Infinity to be refused on toy3")

        // Point(23, 8) is refused because 23 is outside 0 .. 16.
        match EllipticCurve.validatePublicKey EllipticCurve.toy (EllipticCurve.Point(23I, 8I)) with
        | Error _ -> ()
        | Ok () -> Assert.Fail("Expected Point(23, 8) to be refused for out-of-range x")

        // Point(1, 0) is refused because 0^2 = 0 <> 1^3 + 1 = 2 (mod 17).
        match EllipticCurve.validatePublicKey EllipticCurve.toy (EllipticCurve.Point(1I, 0I)) with
        | Error _ -> ()
        | Ok () -> Assert.Fail("Expected Point(1, 0) to be refused as not on toy")

        // On toy2 (Z_4 x Z_4, N = 4), all 15 non-Infinity points pass validatePublicKey because every point order divides 4,
        // even though the subgroup generated by G holds only 3 non-Infinity points.
        let toy2Points = nonInfinityPoints EllipticCurve.toy2
        Assert.Equal(15, toy2Points.Length)
        for pt in toy2Points do
            Assert.Equal(Ok (), EllipticCurve.validatePublicKey EllipticCurve.toy2 pt)

        let gSubgroupNonInfinity =
            [ 1 .. 3 ]
            |> List.map (fun k ->
                [ 1 .. k ]
                |> List.fold (fun acc _ -> EllipticCurve.add EllipticCurve.toy2 acc EllipticCurve.toy2.G) EllipticCurve.Infinity)
            |> List.filter (fun pt -> pt <> EllipticCurve.Infinity)
            |> List.distinct
        Assert.Equal(3, gSubgroupNonInfinity.Length)

    [<Fact>]
    let ``Phase 60 - Invalid-curve point on toy leaks scalar parity and is refused by computeEcdhSharedSecretChecked`` () =
        let curve = EllipticCurve.toy
        let invalidPt = EllipticCurve.Point(1I, 0I)

        // Point(1, 0) is not on toy (y^2 = x^3 + 1), and it is on y^2 = x^3 + 16 modulo 17.
        Assert.False(EllipticCurve.isOnCurve curve invalidPt)
        let x, y = 1I, 0I
        Assert.Equal(Modular.modPos (y * y) 17I, Modular.modPos (x * x * x + 16I) 17I)

        for d in 1I .. 17I do
            let mult = EllipticCurve.scalarMultiply curve d invalidPt
            let isEven = (d % 2I) = 0I
            Assert.Equal(isEven, (mult = EllipticCurve.Infinity))
            match DiffieHellman.computeEcdhSharedSecretChecked curve d invalidPt with
            | Error _ -> ()
            | Ok _ -> Assert.Fail("Expected computeEcdhSharedSecretChecked to refuse invalid-curve point")

        let q = EllipticCurve.scalarMultiply curve 5I curve.G
        let expected = DiffieHellman.computeEcdhSharedSecret curve 7I q
        Assert.Equal(Ok expected, DiffieHellman.computeEcdhSharedSecretChecked curve 7I q)

    [<Fact>]
    let ``Phase 69 - Small-subgroup point Point(0, 1) on toy passes validatePublicKey and leaks d mod 3`` () =
        // Point(0, 1) has order 3 on toy (where N = 18), so it lies on the curve and 18 * Point(0, 1) = Infinity.
        // Contrast this with prime-order toy3 (order 19), where phase 53 showed every point other than Infinity
        // has order 19, so no point of small order exists to send.
        let curve = EllipticCurve.toy
        let smallOrderPt = EllipticCurve.Point(0I, 1I)
        Assert.Equal(Ok (), EllipticCurve.validatePublicKey curve smallOrderPt)

        for d in 1I .. 17I do
            let shared = DiffieHellman.computeEcdhSharedSecret curve d smallOrderPt
            Assert.Equal(Some (d % 3I), DiscreteLog.bruteForce curve smallOrderPt shared)

    [<Fact>]
    let ``Phase 84 - computeEcdhSharedSecretChecked refuses the point at infinity per SEC 1 section 3.3.1 step 2`` () =
        let curve = EllipticCurve.toy
        let smallOrderPt = EllipticCurve.Point(0I, 1I)
        Assert.Equal(Ok (), EllipticCurve.validatePublicKey curve smallOrderPt)

        for d in [ 3I; 6I; 9I; 12I; 15I ] do
            match DiffieHellman.computeEcdhSharedSecretChecked curve d smallOrderPt with
            | Error _ -> ()
            | Ok _ -> Assert.Fail(sprintf "Expected computeEcdhSharedSecretChecked to refuse Infinity for d = %A" d)

        for d in [ 1I; 2I; 4I; 5I; 7I; 8I; 10I; 11I; 13I; 14I; 16I; 17I ] do
            let expected =
                if d % 3I = 1I then EllipticCurve.Point(0I, 1I)
                else EllipticCurve.Point(0I, 16I)
            Assert.Equal(Ok expected, DiffieHellman.computeEcdhSharedSecretChecked curve d smallOrderPt)

        match DiffieHellman.computeEcdhSharedSecretChecked curve 18I curve.G with
        | Error _ -> ()
        | Ok _ -> Assert.Fail("Expected 18 * G = Infinity on toy to be refused")

        match DiffieHellman.computeEcdhSharedSecretChecked EllipticCurve.toy3 19I EllipticCurve.toy3.G with
        | Error _ -> ()
        | Ok _ -> Assert.Fail("Expected 19 * G = Infinity on toy3 to be refused")
