namespace Arcanum.Tests

open Xunit
open Arcanum.Core

module ValidationTests =

    // EllipticCurve.toy, toy2, and toy3 are small curves over F_17 and are not secure groups.

    let private nonInfinityPoints (curve: EllipticCurve.Curve) =
        [ for x in 0I .. curve.P - 1I do
            for y in 0I .. curve.P - 1I do
                let pt = EllipticCurve.Point(x, y)
                if EllipticCurve.isOnCurve curve pt then
                    yield pt ]

    [<Fact>]
    let ``Phase 59 - SEC 1 validatePublicKey on toy3, toy, and toy2`` () =
        let toy3Points = nonInfinityPoints EllipticCurve.toy3
        Assert.Equal(18, toy3Points.Length)
        for pt in toy3Points do
            Assert.Equal(Ok (), EllipticCurve.validatePublicKey EllipticCurve.toy3 pt)

        match EllipticCurve.validatePublicKey EllipticCurve.toy3 EllipticCurve.Infinity with
        | Error _ -> ()
        | Ok () -> Assert.Fail("Expected Infinity to be refused on toy3")

        // Point(23, 8) is refused because 23 is outside 0 .. 16.
        match EllipticCurve.validatePublicKey EllipticCurve.toy (EllipticCurve.Point(23I, 8I)) with
        | Error _ -> ()
        | Ok () -> Assert.Fail("Expected Point(23, 8) to be refused for out-of-range x")

        // Point(1, 0) is refused because 0^2 = 0 <> 1^3 + 1 = 2 (mod 17).
        match EllipticCurve.validatePublicKey EllipticCurve.toy (EllipticCurve.Point(1I, 0I)) with
        | Error _ -> ()
        | Ok () -> Assert.Fail("Expected Point(1, 0) to be refused as not on toy")

        // On toy2 (Z_4 x Z_4, N = 4), all 15 non-Infinity points pass validatePublicKey because every point order divides 4,
        // even though the subgroup generated by G holds only 3 non-Infinity points.
        let toy2Points = nonInfinityPoints EllipticCurve.toy2
        Assert.Equal(15, toy2Points.Length)
        for pt in toy2Points do
            Assert.Equal(Ok (), EllipticCurve.validatePublicKey EllipticCurve.toy2 pt)

        let gSubgroupNonInfinity =
            [ 1 .. 3 ]
            |> List.map (fun k ->
                [ 1 .. k ]
                |> List.fold (fun acc _ -> EllipticCurve.add EllipticCurve.toy2 acc EllipticCurve.toy2.G) EllipticCurve.Infinity)
            |> List.filter (fun pt -> pt <> EllipticCurve.Infinity)
            |> List.distinct
        Assert.Equal(3, gSubgroupNonInfinity.Length)
