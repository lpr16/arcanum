namespace Arcanum.Tests

open System.Numerics
open Xunit
open Arcanum.Core

module DiscreteLogTests =

    // EllipticCurve.toy and toy3 are small curves over F_17 and are not secure groups.
    // DiscreteLog routines are for toy, toy2, and toy3 only.

    let private repeatedAdd (curve: EllipticCurve.Curve) (count: int) (pt: EllipticCurve.ECPoint) =
        [ 1 .. count ]
        |> List.fold (fun acc _ -> EllipticCurve.add curve acc pt) EllipticCurve.Infinity

    [<Fact>]
    let ``Phase 66 - DiscreteLog bruteForce on toy and toy3`` () =
        for k in 0 .. 17 do
            let kG = repeatedAdd EllipticCurve.toy k EllipticCurve.toy.G
            Assert.Equal(Some (BigInteger k), DiscreteLog.bruteForce EllipticCurve.toy EllipticCurve.toy.G kG)

        for k in 0 .. 18 do
            let kG = repeatedAdd EllipticCurve.toy3 k EllipticCurve.toy3.G
            Assert.Equal(Some (BigInteger k), DiscreteLog.bruteForce EllipticCurve.toy3 EllipticCurve.toy3.G kG)

        // G is outside the 3-point subgroup generated by Point(0, 1) on toy.
        Assert.Equal(None, DiscreteLog.bruteForce EllipticCurve.toy (EllipticCurve.Point(0I, 1I)) EllipticCurve.toy.G)

    [<Fact>]
    let ``Phase 67 - DiscreteLog babyStepGiantStep on toy and toy3`` () =
        Assert.Equal(5I, DiscreteLog.ceilSqrt 18I)
        Assert.Equal(5I, DiscreteLog.ceilSqrt 19I)
        Assert.Equal(2I, DiscreteLog.ceilSqrt 3I)

        for k in 0 .. 17 do
            let kG = repeatedAdd EllipticCurve.toy k EllipticCurve.toy.G
            let bsgs = DiscreteLog.babyStepGiantStep EllipticCurve.toy EllipticCurve.toy.G kG 18I
            Assert.Equal(Some (BigInteger k), bsgs)
            Assert.Equal(DiscreteLog.bruteForce EllipticCurve.toy EllipticCurve.toy.G kG, bsgs)

        for k in 0 .. 18 do
            let kG = repeatedAdd EllipticCurve.toy3 k EllipticCurve.toy3.G
            let bsgs = DiscreteLog.babyStepGiantStep EllipticCurve.toy3 EllipticCurve.toy3.G kG 19I
            Assert.Equal(Some (BigInteger k), bsgs)
            Assert.Equal(DiscreteLog.bruteForce EllipticCurve.toy3 EllipticCurve.toy3.G kG, bsgs)

        Assert.Equal(
            None,
            DiscreteLog.babyStepGiantStep EllipticCurve.toy (EllipticCurve.Point(0I, 1I)) EllipticCurve.toy.G 3I)

    [<Fact>]
    let ``Phase 68 - DiscreteLog pohligHellman on toy and toy3`` () =
        let toyFactors = [ (2I, 1); (3I, 2) ]
        for k in 0 .. 17 do
            let kG = repeatedAdd EllipticCurve.toy k EllipticCurve.toy.G
            Assert.Equal(Ok (BigInteger k), DiscreteLog.pohligHellman EllipticCurve.toy EllipticCurve.toy.G kG toyFactors)

        let toy3Factors = [ (19I, 1) ]
        for k in 0 .. 18 do
            let kG = repeatedAdd EllipticCurve.toy3 k EllipticCurve.toy3.G
            Assert.Equal(Ok (BigInteger k), DiscreteLog.pohligHellman EllipticCurve.toy3 EllipticCurve.toy3.G kG toy3Factors)

        // Product 2 * 3 = 6 <> 18 (the order of G on toy), so pohligHellman returns Error.
        match DiscreteLog.pohligHellman EllipticCurve.toy EllipticCurve.toy.G EllipticCurve.toy.G [ (2I, 1); (3I, 1) ] with
        | Error _ -> ()
        | Ok _ -> Assert.Fail("Expected pohligHellman to refuse factors whose product is not the order of G")
